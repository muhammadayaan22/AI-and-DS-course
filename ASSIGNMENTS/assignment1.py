# Arithmetic Operators
a = 15
b = 4

print("Addition: a + b =", a + b)
print("Subtraction: a - b =", a - b)
print("Multiplication: a * b =", a * b)
print("Division: a / b =", a / b)
print("Floor Division: a // b =", a // b)
print("Modulus: a % b =", a % b)
print("Exponentiation: a * b =", a * b)

# A: Floor Division (15 // 4) = 3
#    Modulus (15 % 4) = 3

# Assignment Operators
x = 10
print("Initial value of x:", x)

x += 5
print("After x += 5:", x)

x *= 2
print("After x *= 2:", x)

x -= 4
print("After x -= 4:", x)

x /= 2
print("After x /= 2:", x)
# A: ((10 + 5) * 2 - 4) / 2 = (30 - 4) / 2 = 26 / 2 = 13.0

# Comparison Operators
a = 7
b = 10

print("a == b:", a == b)
print("a != b:", a != b)
print("a > b:", a > b)
print("a < b:", a < b)
print("a >= b:", a >= b)
print("a <= b:", a <= b)

# A: a != b, a < b, a <= b



# Logical Operators
x = True
y = False

print("x and y:", x and y)
print("x or y:", x or y)
print("not x:", not x)

# Membership Operators
institute = "Saylani Mass IT"

print("'s' in institute:", 's' in institute)
print("'Mass' in institute:", 'Mass' in institute)
print("'Saylani' not in institute:", 'Saylani' not in institute)

# Identity Operators
a = 5
b = 5
c = 1000

print("a is b:", a is b)        
print("a is c:", a is c)         
print("c is not b:", c is not b)
